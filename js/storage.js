// 次の起動で残りを片付けられる順番にします。すべて終わるまでリセット完了とは表示しません。
// 旧カードから届く書き込みは現在のIDと照合して止めます。古いURLには無効になったことを伝えます。
// 確認　旧カードを開いたままリセットし、旧ID・登録名・配置・履歴・報告・当選が戻らないか。
