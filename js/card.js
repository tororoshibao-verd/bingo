// 書く順番は game.js の抽選・カード・判定 → storage.js の保存・読込 → draw.js の準備・発行 → 下の手順。
// まず自分のカードが1枚復元できるところまで作り、その後で変更通知や同時操作を試しましょう。

// 手順1　開いたタブが「どのゲームの、どのカード」かを調べる
// ページを開いたとき、URLの gameId と cardId を取り出す。発行した draw.js が付ける2つの目印です。
// storage.js の短い書き込み用の鍵を取り、現在のゲーム・発行済みID・このカードの記録を読みます。
// 別ゲームは旧カード、発行されていないIDは無効なURL。登録済みなら配置と名前を復元して手順3へ。
// 締切後の未登録は受付終了。準備中で「未作成」の発行票がある場合だけ game.js で25マスを生成し、
// このカード専用のキーに「未登録」と配置を一緒に保存します。これで手順2の入力画面へ進めます。
// すでに未登録の配置があれば、それを復元して手順2へ。発行票の欠損、配置の欠落や破損はエラーです。
// 読み直しから保存までを同じ短い鍵の中で一度に進め、同じURLを同時に開いても配置を作り直さないようにします。
// body の data-card-state は見せ方だけを切り替える。HTMLにある playing や CARD-003 は判断材料にしない。
// 不正・破損時は #card-error-reason に理由を表示して止める。復元の失敗を新規発行として扱わない。
// 確認　名前の入力前に同じURLを2回開き、保存された25マスは同じで参加人数は増えていませんか？
// IDなし、未発行ID、古いURL、保存済み配置の欠損も試し、新しい配置が作られないことを確認します。

// 手順2　保存済みの配置に名前を付け、参加を確定する
// register の画面では #entry-id と #fallback-id に自分のカードIDを表示する。登録の操作は #register-card。
// メモ帳で使ったクリックイベントと入力値の取得を応用する。初期表示時にこのボタンのイベントを一度だけ登録する。
// #entry-name の入力を読み、空白だけならカードIDを採用する。空欄の代わりのIDには10文字制限を掛けない。
// 名前が11文字以上なら #entry-feedback の hidden を外し、理由を示して止める。短く切って勝手に確定しない。
// 文字数は参加者が入力する名前で数える。絵文字などを一文字として扱う場合は、見た目の一文字単位で数える方法を調べる。
// 保存直前の競合にも注意。開始処理と同じ短い鍵の中で、現在のゲーム・発行済みID・受付状態・カードを再読する。
// 同じURLを別タブで先に登録していたら、その名前と配置を復元する。名前の編集や二枚目の生成に進まない。
// 未登録で受付中なら、手順1の配置をそのまま引き継ぎ、表示名と登録確定状態を同じ記録に保存する。
// 受付終了、旧ID、未発行、保存済みであるはずの配置の欠損・破損なら、その時点で登録を止める。
// 保存成功後だけ入力欄を閉じる。失敗時は #entry-feedback を表示し、未登録のまま再試行できるようにする。
// 確認　空文字・空白・10文字・11文字、二重クリック、同一URLの同時登録、開始と登録の同時操作を試す。

// 手順3　読み込んだ自分の情報から盤面を表示する
// 登録後・再読み込み時は、保存済みカードのID、表示名、配置を受け取る。数字の範囲・個数・中央FREEを先に検証する。
// #card-id と #card-name にテキストとして値を入れる。名前に「<」などが含まれても文字として表示できる方法を使う。
// #card-grid の tbody は、最初に見本の行を取り除き、保存した5行×5列で一度だけ組み立て直す。
// 席決めで列を意識したのと同様、for で「今何行・何列か」をたどる。数字マスには data-number、中央には .free-cell を付ける。
// まだ抽選が0回なら #card-round を抽選待ちにし、サンプルの N や 42 とマスの印を消す。FREEだけは開いている。
// 準備中の登録済みカードでは .card-badge.state-playing も「開始待ち」にする。登録済みかとゲームの開始は別の状態。
// 確認　同じURLの更新と再表示で、配置・名前が一致するか。長い代替IDも末尾まで表示できるか。

// 手順4　確定した履歴全体に照らして、自分のマスと最新番号を更新する
// 画面を開いたとき、タブに戻ったとき、関連する保存が変わったときに同じ更新手順を呼ぶ。
// storage.js の変更通知は「読み直すきっかけ」。取りこぼしや他タブの遅れがあるので、最新1個だけを付け足さない。
// game.js に保存済みの配置と順序付き抽選履歴を渡し、開いたマス・初ビンゴの回数を受け取る。
// #card-grid の数字マスを順に見て .is-open を結果に合わせる。抽選済みなら読み上げ用の .sr-only にもその状態を示す。
// 履歴の末尾から #card-letter と #card-number を、履歴の長さから #card-round を更新する。空の履歴に末尾はない。
// 確認　参加者タブを閉じたまま数回進め、同じURLを開き直す。途中で出た番号も全て開くか、中央は常にFREEか。

// 手順5　今回の抽選まで確認したことと、自分のビンゴ結果を一緒に報告する
// 手順4が完了した時、当たっていないカードもすでに当たったカードも報告の対象。登録前や旧ゲームは送らない。
// 自分の gameId・cardId、確認済み回数 checkedDrawCount、ビンゴ有無、最初の成立回 firstBingoAt を一組にする。
// ビンゴがない場合の成立回は null。休んでいたタブが復帰した場合も、初めて揃った当時の回を履歴から求める。
// storage.js に渡し「このゲームのこのカード」専用の報告を一度の保存で更新する。全員分の一覧を書き戻さない。
// 同じカードを複数タブで開けるので、書く直前に共有の鍵の中でゲーム・状態・保存済み報告を確認する。
// すでに同じ回・同じ結果なら再保存せず、より新しい報告なら古い回で上書きしない。通知と保存の往復も防げる。
// 同じ内容の遅着は二重申告にしない。別ゲーム・未来の回数・配置不整合は中断し、表示できる理由を示す。
// 保存成功または同じ報告の保存済み確認後に #card-sync を更新する。自分の保存による他タブ通知を待たない。
// 確認　同時に2枚が揃った回に両方の報告が残るか。ビンゴ済みカードでも次回の確認回数は進むか。

// 手順6　進行役による確定・終了・リセットを受け取る
// 申告しただけでは当選確定ではない。draw.js が確定保存した結果から自分の gameId と cardId を照合する。
// 確定があれば #card-result に自分の結果だけを表示する。メモ帳の要素追加を使うときも同じ結果を重ねて追加しない。
// 進行役の最終確認中は最後の回まで手順4・5を行う。終了確定後は ended にし、確定履歴と盤面を読むだけにする。
// 自分の表示が遅れて代替照合された場合も、確認済み回数を巻き戻さず、当選者一覧は draw.js に任せる。
// リセットで gameId が変わったら reset に切り替え、古い名前・カード・番号・結果を無効化し、保留中の書き込みも止める。
// 確認　終了後は最後のカードが見えるか。旧URLでは新ゲームの表示・登録ができず、他の人の当選通知も出ないか。
